// Prueba de integración explícita. Requiere Docker Desktop; no usa proyectos ni claves reales.
// Ejecutar: node tests/contrato-docker.mjs
import assert from "node:assert/strict";
import crypto from "node:crypto";
import net from "node:net";
import os from "node:os";
import path from "node:path";
import { mkdtemp, rm } from "node:fs/promises";
import { spawn } from "node:child_process";
import { armarProyecto } from "../lib/implementacion.js";

const raiz = await mkdtemp(path.join(os.tmpdir(), "icase-contrato-"));
const reserva = net.createServer();
await new Promise((resolve) => reserva.listen(0, "127.0.0.1", resolve));
const puerto = reserva.address().port;
await new Promise((resolve) => reserva.close(resolve));
const token = crypto.randomBytes(32).toString("hex");
const runner = spawn(process.execPath, ["runner/index.mjs"], { cwd: process.cwd(), env: { ...process.env, RUNNER_PORT: String(puerto), RUNNER_TOKEN: token, WORKSPACES_DIR: raiz }, windowsHide: true, stdio: ["ignore", "pipe", "pipe"] });
let salida = "";
runner.stdout.on("data", (d) => { salida += d; }); runner.stderr.on("data", (d) => { salida += d; });
const api = `http://127.0.0.1:${puerto}`;
const headers = { Authorization: `Bearer ${token}`, "Content-Type": "application/json" };
const sql = `
create table public.registro (id integer generated by default as identity primary key, titulo text not null);
alter table public.registro enable row level security;
grant select,insert,update,delete on public.registro to authenticated;
grant usage,select on sequence public.registro_id_seq to authenticated;
create policy lectura on public.registro for select to authenticated using (true);
create policy crear on public.registro for insert to authenticated with check (auth.jwt()->'app_metadata'->>'rol' = 'Administrador');
create policy editar on public.registro for update to authenticated using (auth.jwt()->'app_metadata'->>'rol' = 'Administrador') with check (auth.jwt()->'app_metadata'->>'rol' = 'Administrador');
create policy borrar on public.registro for delete to authenticated using (auth.jwt()->'app_metadata'->>'rol' = 'Administrador');
create function public.contar_registros() returns integer language sql stable security invoker set search_path=public as 'select count(*)::integer from public.registro';
create function public.solo_admin() returns integer language plpgsql security definer set search_path=public as $$ begin
if auth.jwt()->'app_metadata'->>'rol' is distinct from 'Administrador' then raise insufficient_privilege using message='Solo administrador'; end if;
return (select count(*)::integer from public.registro); end $$;
grant execute on function public.contar_registros(),public.solo_admin() to authenticated;
`;
const seed = `insert into public.registro(titulo) values ('Registro de prueba');
insert into auth.users(instance_id,id,aud,role,email,encrypted_password,email_confirmed_at,raw_app_meta_data,raw_user_meta_data,created_at,updated_at,confirmation_token,email_change,email_change_token_new,recovery_token) values
('00000000-0000-0000-0000-000000000000','11111111-1111-4111-8111-111111111111','authenticated','authenticated','administrador@prueba.local',extensions.crypt('Prueba123!',extensions.gen_salt('bf')),now(),'{"provider":"email","providers":["email"],"rol":"Administrador"}','{}',now(),now(),'','','',''),
('00000000-0000-0000-0000-000000000000','22222222-2222-4222-8222-222222222222','authenticated','authenticated','operador@prueba.local',extensions.crypt('Prueba123!',extensions.gen_salt('bf')),now(),'{"provider":"email","providers":["email"],"rol":"Operador"}','{}',now(),now(),'','','','');
insert into auth.identities(id,provider_id,user_id,identity_data,provider,created_at,updated_at) select gen_random_uuid(),id::text,id,jsonb_build_object('sub',id::text,'email',email,'email_verified',true),'email',now(),now() from auth.users;
`;
try {
  for (let i = 0; i < 100; i++) {
    if (runner.exitCode !== null) throw new Error(salida);
    if (await fetch(`${api}/salud`, { headers }).then((r) => r.ok).catch(() => false)) break;
    await new Promise((resolve) => setTimeout(resolve, 100));
  }
  const { archivos } = await armarProyecto({ nombre: "Contrato integración", piezas: [{ pieza: "supabase", opcionales: ["auth"] }], generados: [{ ruta: "supabase/migrations/0001_registro.sql", contenido: sql }, { ruta: "supabase/seed.sql", contenido: seed }] });
  const actores = [{ nombre: "Administrador" }, { nombre: "Operador" }];
  const todos = actores.map((a) => a.nombre);
  const operaciones = [
    { id: "leer", tipo: "tabla", recurso: "registro", metodo: "GET", roles: todos, prueba: { filtros: { id: "eq.1" } } },
    { id: "crear", tipo: "tabla", recurso: "registro", metodo: "POST", roles: [todos[0]], prueba: { cuerpo: { titulo: "Creado en transacción revertida" } } },
    { id: "editar", tipo: "tabla", recurso: "registro", metodo: "PATCH", roles: [todos[0]], prueba: { filtros: { id: "eq.1" }, cuerpo: { titulo: "Editado" } } },
    { id: "borrar", tipo: "tabla", recurso: "registro", metodo: "DELETE", roles: [todos[0]], prueba: { filtros: { id: "eq.1" } } },
    { id: "rpc", tipo: "rpc", recurso: "contar_registros", metodo: "POST", roles: todos, prueba: { cuerpo: {} } },
    { id: "rpc_admin", tipo: "rpc", recurso: "solo_admin", metodo: "POST", roles: [todos[0]], prueba: { cuerpo: {} } },
    // Tras borrar por HTTP la fila debe seguir existiendo para ambos actores.
    { id: "leer_despues", tipo: "tabla", recurso: "registro", metodo: "GET", roles: todos, prueba: { filtros: { id: "eq.1" } } },
  ];
  const respuesta = await fetch(`${api}/proyectos/test-contrato/probarbd`, { method: "POST", headers, body: JSON.stringify({ archivos, servicio: "migraciones", modo: "tarea", conexion: { usuario: "postgres", baseDatos: "postgres" }, inventario: true, contrato: { operaciones }, actores }), signal: AbortSignal.timeout(290_000) });
  const resultado = await respuesta.json();
  if (!respuesta.ok || !resultado.ok) throw new Error(JSON.stringify(resultado));
  assert.ok(resultado.inventario.tablas.some((t) => t.nombre === "registro" && t.columnas.some((c) => c.nombre === "id" && c.primaria)));
  assert.ok(resultado.inventario.funciones.some((f) => f.nombre === "solo_admin" && f.securityDefiner));
  assert.equal(resultado.pruebaContrato.ok, true, JSON.stringify(resultado.pruebaContrato));
  assert.equal(resultado.pruebaContrato.correctas, 16);
  console.log("Integración Docker correcta: inventario, login de dos actores, CRUD, RPC y rollback; 16 comprobaciones.");
  const segundo = await armarProyecto({ nombre: "Taller de integración", piezas: [{ pieza: "postgres" }], generados: [{ ruta: "database/init/01_ordenes.sql", contenido: "create table public.orden_servicio(id integer primary key, descripcion text not null); insert into public.orden_servicio values(1,'Cambio de aceite');" }] });
  const respTaller = await fetch(`${api}/proyectos/test-contrato-taller/probarbd`, { method: "POST", headers, body: JSON.stringify({ archivos: segundo.archivos, servicio: "db", modo: "servicio", conexion: { usuario: "${DB_USER}", baseDatos: "${DB_NAME}" }, inventario: true }), signal: AbortSignal.timeout(180_000) });
  const taller = await respTaller.json();
  assert.ok(respTaller.ok && taller.ok, JSON.stringify(taller));
  assert.ok(taller.inventario.tablas.some((t) => t.nombre === "orden_servicio"));
  console.log("Segundo proyecto correcto: inventario PostgreSQL de órdenes de taller sin Supabase.");
  if (process.env.PROBAR_IA === "1") {
    const { generarContrato } = await import("../lib/contrato.js");
    const contexto = {
      nombre: "Registro de partes", analisis: { actores, requerimientos_funcionales: [{ codigo: "RF01", nombre: "Consultar partes", descripcion: "El sistema debe permitir consultar los registros a ambos actores.", actores: todos }, { codigo: "RF02", nombre: "Crear registro", descripcion: "El sistema debe permitir crear registros solo al Administrador.", actores: [todos[0]] }] },
      pantallas: [{ nombre: "Registros", plataforma: "Web", rfs: ["RF01", "RF02"], html: '<button>Consultar registros</button><form aria-label="Crear registro"><input name="titulo"><button type="submit">Guardar registro</button></form>' }],
      stack: { piezas: [{ pieza: "supabase", opcionales: ["auth"] }] }, sql: [{ ruta: "0001.sql", contenido: sql }, { ruta: "seed.sql", contenido: seed }], inventario: resultado.inventario, usarClaude: false,
    };
    const generado = await generarContrato(contexto);
    assert.deepEqual(generado.errores, [], JSON.stringify(generado.errores));
    assert.equal(generado.cobertura.acciones[0], generado.cobertura.acciones[1]);
    console.log(`IA real Supabase correcta: ${generado.operaciones.length} operaciones; ${generado.modelo_ia}.`);
    const generadoExpress = await generarContrato({ ...contexto, nombre: "Órdenes de taller", stack: { piezas: [{ pieza: "express" }, { pieza: "postgres" }] }, inventario: taller.inventario, sql: [], pantallas: [{ nombre: "Órdenes", rfs: ["RF01", "RF02"], html: '<button>Consultar órdenes</button><button>Crear orden de servicio</button>' }] });
    assert.deepEqual(generadoExpress.errores, [], JSON.stringify(generadoExpress.errores));
    assert.match(generadoExpress.openapi, /openapi: 3\.0\.3/);
    console.log(`IA real Express correcta: ${generadoExpress.operaciones.length} operaciones; ${generadoExpress.modelo_ia}.`);
  }
} finally {
  runner.kill();
  await new Promise((resolve) => { if (runner.exitCode !== null) resolve(); else runner.once("exit", resolve); });
  // La carpeta la creó este script dentro del temporal del sistema.
  if (!path.resolve(raiz).startsWith(path.resolve(os.tmpdir()) + path.sep) || !path.basename(raiz).startsWith("icase-contrato-")) throw new Error("Carpeta temporal no válida para limpiar.");
  await rm(raiz, { recursive: true, force: true });
}
